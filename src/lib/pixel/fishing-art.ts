// ---- 釣り糸 ----
// 竿の穂先から浮きの糸の端(浮きの絵の上の s)までを渡す 1 ドットの糸。色も浮きの糸と同じ s。
// CSS で線を引かずに絵として焼くのは、色をシートの中だけに置き、昼夜の色替えも地形と同じ
// phasePalette に任せるため。
// 浮きは必ず主人公の 1 マス先に置かれる。糸が見えている間の主人公は待つ・身構える・引き込まれるの
// 3 コマ(actors.ts の fish・tense・bite)を行き来するが、3 コマとも向きごとに同じ穂先を残してあるので、
// 糸の形は向きごとに 1 枚で決まる。穂先か浮きの糸を動かしたら、ここも描き直す
// (sprites-art.test.ts が 4 向き × 主人公 3 コマ × 浮き 2 コマ × 沈み 2 通りでつながりを確かめている)。
// 座標は (列, 行) のドットで、主人公が立つマスの左上を (0, 0) とする。主人公の絵は頭が
// 半マス上へはみ出すので、竿の絵の行 r はこの座標の r - 8 行に来る。
//
// 浮きの糸(浮きのマスの 7 列目)は、投げた浮きで 1〜3 行、かかった浮きで 3〜5 行にある。
// 糸の絵はどの向きでもこの列を 5 行目まで下ろしておき、どのコマでも途切れないようにする。
// 投げた浮きとは 1〜3 行が同じ色で重なり、4・5 行は玉の頭(x・r)の下に隠れる。
// かかった浮きでは沈んだぶんの 1・2 行を糸が埋め、3〜5 行は浮きの糸と同じ色で重なる。
